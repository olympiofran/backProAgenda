CREATE SCHEMA IF NOT EXISTS pi_fran;

DROP TABLE IF EXISTS pi_fran.agendamentos CASCADE;
DROP TABLE IF EXISTS pi_fran.codigos_recuperacao CASCADE;
DROP TABLE IF EXISTS pi_fran.clientes CASCADE;
DROP TABLE IF EXISTS pi_fran.servicos CASCADE;
DROP TABLE IF EXISTS pi_fran.cadastro CASCADE;

-- Conta do profissional. servico guarda a atividade (role do frontend).
-- dia e horario permanecem no schema pedido; a agenda fica em agendamentos.
CREATE TABLE pi_fran.cadastro (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(30),
  telefone VARCHAR(20),
  email VARCHAR(100) UNIQUE,
  senha VARCHAR(255),
  servico VARCHAR(30),
  dia DATE,
  horario TIME
);

CREATE TABLE pi_fran.clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cadastro_id INTEGER NOT NULL REFERENCES pi_fran.cadastro (id) ON UPDATE CASCADE ON DELETE CASCADE,
  nome VARCHAR(100) NOT NULL,
  telefone VARCHAR(20) NOT NULL,
  email VARCHAR(100),
  observacoes TEXT,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX clientes_cadastro_id_nome_index ON pi_fran.clientes (cadastro_id, nome);

CREATE TABLE pi_fran.servicos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cadastro_id INTEGER NOT NULL REFERENCES pi_fran.cadastro (id) ON UPDATE CASCADE ON DELETE CASCADE,
  nome VARCHAR(100) NOT NULL,
  duracao_minutos INTEGER NOT NULL CHECK (duracao_minutos >= 0),
  preco NUMERIC(10, 2) NOT NULL,
  categoria VARCHAR(40) NOT NULL DEFAULT 'Geral',
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX servicos_cadastro_id_nome_index ON pi_fran.servicos (cadastro_id, nome);

CREATE TABLE pi_fran.agendamentos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cadastro_id INTEGER NOT NULL REFERENCES pi_fran.cadastro (id) ON UPDATE CASCADE ON DELETE CASCADE,
  cliente_id INTEGER REFERENCES pi_fran.clientes (id) ON UPDATE CASCADE ON DELETE SET NULL,
  servico_id INTEGER NOT NULL REFERENCES pi_fran.servicos (id) ON UPDATE CASCADE ON DELETE RESTRICT,
  cliente_nome VARCHAR(100),
  data DATE NOT NULL,
  inicio TIME NOT NULL,
  fim TIME NOT NULL,
  preco NUMERIC(10, 2) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'confirmado' CHECK (status IN ('confirmado', 'cancelado')),
  observacoes TEXT,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX agendamentos_cadastro_id_data_index ON pi_fran.agendamentos (cadastro_id, data);

CREATE TABLE pi_fran.codigos_recuperacao (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cadastro_id INTEGER NOT NULL REFERENCES pi_fran.cadastro (id) ON UPDATE CASCADE ON DELETE CASCADE,
  codigo_hash VARCHAR(64) NOT NULL,
  verificado BOOLEAN NOT NULL DEFAULT FALSE,
  expira_em TIMESTAMP NOT NULL,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX codigos_recuperacao_cadastro_id_index ON pi_fran.codigos_recuperacao (cadastro_id);

